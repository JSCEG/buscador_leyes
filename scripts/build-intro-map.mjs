/**
 * Builds src/lib/mexico-map.js for the entrance animation: the 32 states as light SVG paths
 * (projected and simplified) plus one point inside each state. Source: the same states layer the
 * permits map uses. Run: node scripts/build-intro-map.mjs
 */
import { writeFileSync } from 'node:fs';
import { STATES_URL } from '../server/mapa-proxy.js';

const WIDTH = 1000;
const TOLERANCE = 2.2; // px in the output viewBox
const MIN_RING_AREA = 40; // drop islets smaller than this (px²)

const geo = await (await fetch(STATES_URL)).json();
const rings = feature => (feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates).map(poly => poly[0]);

// Equirectangular projection scaled by the cosine of Mexico's mid latitude.
let [minLon, maxLon, minLat, maxLat] = [Infinity, -Infinity, Infinity, -Infinity];
for (const feature of geo.features) for (const ring of rings(feature)) for (const [lon, lat] of ring) {
    minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
    minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
}
const k = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180);
const scale = WIDTH / ((maxLon - minLon) * k);
const HEIGHT = Math.round((maxLat - minLat) * scale);
const project = ([lon, lat]) => [(lon - minLon) * k * scale, (maxLat - lat) * scale];

function simplify(points, tolerance) {
    if (points.length < 3) return points;
    const keep = new Uint8Array(points.length);
    keep[0] = keep[points.length - 1] = 1;
    const stack = [[0, points.length - 1]];
    while (stack.length) {
        const [a, b] = stack.pop();
        const [ax, ay] = points[a];
        const [bx, by] = points[b];
        const len = Math.hypot(bx - ax, by - ay) || 1;
        let worst = -1;
        let index = -1;
        for (let i = a + 1; i < b; i++) {
            const d = Math.abs((bx - ax) * (ay - points[i][1]) - (ax - points[i][0]) * (by - ay)) / len;
            if (d > worst) { worst = d; index = i; }
        }
        if (worst > tolerance) { keep[index] = 1; stack.push([a, index], [index, b]); }
    }
    return points.filter((_, i) => keep[i]);
}
// A closed ring starts and ends on the same point: split it at the farthest point and simplify both halves.
function simplifyRing(ring, tolerance) {
    const [x0, y0] = ring[0];
    let far = 1;
    ring.forEach(([x, y], i) => { if (Math.hypot(x - x0, y - y0) > Math.hypot(ring[far][0] - x0, ring[far][1] - y0)) far = i; });
    return [...simplify(ring.slice(0, far + 1), tolerance).slice(0, -1), ...simplify(ring.slice(far), tolerance)];
}
const area = ring => Math.abs(ring.reduce((sum, [x, y], i) => { const [nx, ny] = ring[(i + 1) % ring.length]; return sum + x * ny - nx * y; }, 0)) / 2;

const states = geo.features.map(feature => {
    const projected = rings(feature).map(ring => ring.map(project)).filter(ring => area(ring) >= MIN_RING_AREA);
    const largest = projected.reduce((best, ring) => (area(ring) > area(best) ? ring : best), projected[0]);
    const d = projected.map(ring => simplifyRing(ring, TOLERANCE)).filter(ring => ring.length > 3)
        .map(ring => 'M' + ring.map(([x, y]) => `${x.toFixed(0)} ${y.toFixed(0)}`).join('L') + 'Z').join('');
    // A point inside the state: the centroid of its largest ring.
    const [cx, cy] = largest.reduce(([sx, sy], [x, y]) => [sx + x / largest.length, sy + y / largest.length], [0, 0]);
    return { d, at: [Math.round(cx), Math.round(cy)] };
}).filter(state => state.d);

const out = `// Generated by scripts/build-intro-map.mjs from the states layer of the permits map. Do not edit.
export const MEXICO_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';
export const MEXICO_STATES = ${JSON.stringify(states)};
`;
writeFileSync(new URL('../src/lib/mexico-map.js', import.meta.url), out);
console.log(`${states.length} states, ${Math.round(out.length / 1024)} KB, viewBox ${WIDTH}×${HEIGHT}`);
